#!/usr/bin/env node
/**
 * 生成 src/client/pdf-resources-data.js：把 pdf.js 运行时按需加载的二进制资源
 * 内嵌进客户端产物，让扫描版 PDF（JBIG2 / OpenJPEG 图片、中文 CMap）在
 * 无网络环境下也能解码（对照原版 qiaomu-reader 4.5.13）。
 *
 * - CMaps：只嵌入繁中文档常用的子集（Adobe-CNS1 / Big5 / CNS / ETen / HK）；
 * - wasm：jbig2 / openjpeg / qcms 三个解码器，deflate 压缩后拼成一个 zip，
 *   运行时用 src/core/zip.js 解出（免新增依赖），每次调用返回全新字节，
 *   因为 pdf.js 可能会把缓冲区 transfer 给 worker。
 *
 * 用法：node scripts/generate-pdf-resources.mjs（npm install 后跑一次即可，
 * 产物是生成文件，随源码提交；构建脚本不会自动重跑）。
 */
import { deflateRawSync } from 'node:zlib';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cmapsDir = path.join(root, 'node_modules', 'pdfjs-dist', 'cmaps');
const wasmDir = path.join(root, 'node_modules', 'pdfjs-dist', 'wasm');
const output = path.join(root, 'src', 'client', 'pdf-resources-data.js');

const traditionalChineseCMap = /(?:Adobe-CNS1|B5|CNS|ETen|HK).*\.bcmap$/;
const wasmNames = ['jbig2.wasm', 'openjpeg.wasm', 'qcms_bg.wasm'];

// ── CMaps ────────────────────────────────────────────────────────────────
const cmapNames = fs.readdirSync(cmapsDir).filter((name) => traditionalChineseCMap.test(name)).sort();
if (!cmapNames.includes('Adobe-CNS1-UCS2.bcmap')) {
  throw new Error('pdf.js 繁体中文 CMaps 未找到；请先 npm install');
}
const cmapEntries = cmapNames.map((name) => {
  const encoded = fs.readFileSync(path.join(cmapsDir, name)).toString('base64');
  return `  ${JSON.stringify(name)}: ${JSON.stringify(encoded)},`;
});

// ── wasm zip（最小 zip 写入器：deflate 条目 + 中央目录 + EOCD）────────────
const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i += 1) {
    let c = i;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[i] = c >>> 0;
  }
  return table;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** DOS 时间戳：固定 2000-01-01，保证产物确定性 */
const DOS_TIME = 0;
const DOS_DATE = (20 << 9) | (1 << 5) | 1;

function u16(value) { return [value & 0xff, (value >>> 8) & 0xff]; }
function u32(value) { return [value & 0xff, (value >>> 8) & 0xff, (value >>> 16) & 0xff, (value >>> 24) & 0xff]; }

function buildZip(files) {
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const { name, data } of files) {
    const nameBytes = Buffer.from(name, 'utf8');
    const compressed = deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.concat([
      Buffer.from(u32(0x04034b50)),
      Buffer.from(u16(20)), Buffer.from(u16(0)),
      Buffer.from(u16(8)), Buffer.from(u16(DOS_TIME)), Buffer.from(u16(DOS_DATE)),
      Buffer.from(u32(crc)), Buffer.from(u32(compressed.length)), Buffer.from(u32(data.length)),
      Buffer.from(u16(nameBytes.length)), Buffer.from(u16(0)),
      nameBytes, compressed,
    ]);
    locals.push(local);
    const central = Buffer.concat([
      Buffer.from(u32(0x02014b50)),
      Buffer.from(u16(20)), Buffer.from(u16(20)),
      Buffer.from(u16(0)), Buffer.from(u16(8)),
      Buffer.from(u16(DOS_TIME)), Buffer.from(u16(DOS_DATE)),
      Buffer.from(u32(crc)), Buffer.from(u32(compressed.length)), Buffer.from(u32(data.length)),
      Buffer.from(u16(nameBytes.length)),
      Buffer.from(u16(0)), Buffer.from(u16(0)), Buffer.from(u16(0)), Buffer.from(u16(0)), Buffer.from(u32(0)),
      Buffer.from(u32(offset)),
      nameBytes,
    ]);
    centrals.push(central);
    offset += local.length;
  }
  const centralDir = Buffer.concat(centrals);
  const eocd = Buffer.concat([
    Buffer.from(u32(0x06054b50)),
    Buffer.from(u16(0)), Buffer.from(u16(0)),
    Buffer.from(u16(files.length)), Buffer.from(u16(files.length)),
    Buffer.from(u32(centralDir.length)), Buffer.from(u32(offset)),
    Buffer.from(u16(0)),
  ]);
  return Buffer.concat([...locals, centralDir, eocd]);
}

const wasmFiles = wasmNames.map((name) => {
  const data = fs.readFileSync(path.join(wasmDir, name));
  if (!data.subarray(0, 4).equals(Buffer.from([0x00, 0x61, 0x73, 0x6d]))) {
    throw new Error(`pdf.js wasm 资源异常（缺少 \\0asm 魔数）：${name}`);
  }
  return { name, data };
});
const wasmArchive = buildZip(wasmFiles).toString('base64');

fs.writeFileSync(output, [
  '// Generated by scripts/generate-pdf-resources.mjs from pdfjs-dist. Do not edit by hand.',
  'export const EMBEDDED_PDF_CMAPS = Object.freeze({',
  ...cmapEntries,
  '});',
  '',
  `export const EMBEDDED_PDF_WASM_ARCHIVE = ${JSON.stringify(wasmArchive)};`,
  '',
].join('\n'));

const raw = wasmFiles.reduce((sum, file) => sum + file.data.length, 0);
console.log(`已嵌入 ${cmapNames.length} 个繁体中文 PDF CMaps`);
console.log(`已嵌入 ${wasmFiles.length} 个压缩的离线 PDF 图像/颜色解码器（原始 ${raw} 字节 → zip ${wasmArchive.length} base64 字符）`);
